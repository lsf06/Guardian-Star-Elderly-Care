# ============================================================ 工具函数

def git(*args: str) -> str:
    r = subprocess.run(["git", *args], capture_output=True, text=True, encoding="utf-8")
    if r.returncode != 0:
        sys.exit(f"git {' '.join(args)} 失败：{r.stderr.strip()}")
    return r.stdout


def flatten(text: str, limit: int = 260) -> str:
    """多行压成一行。Bitable 的 CSV 导入对单元格内换行支持不稳，统一用「；」。"""
    text = text.replace("\\n", "\n").replace("\r", "")  # 提交正文里偶有字面量 \n
    lines = [ln.strip().lstrip("-·* ").strip() for ln in text.split("\n")]
    joined = "；".join(ln for ln in lines if ln)
    joined = re.sub(r"\s{2,}", " ", joined)
    joined = re.sub(r"；+", "；", joined).strip("；")
    if len(joined) > limit:
        joined = joined[:limit].rstrip("；，,。 ") + "…"
    return joined


def write_csv(name: str, fields: list[str], rows: list[dict]) -> Path:
    path = OUT / name
    # utf-8-sig：不带 BOM 的话，Windows 版 Excel 与飞书导入都会把中文读成乱码
    with path.open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    return path


