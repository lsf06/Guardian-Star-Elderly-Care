def build_log() -> list[dict]:
    raw = git("log", "--pretty=format:@@%H|%ad|%s|%b", "--date=format:%Y-%m-%d", "--shortstat")
    rows: list[dict] = []
    for block in raw.split("@@")[1:]:
        block = block.strip()
        if not block:
            continue
        head, _, rest = block.partition("\n")
        full_hash, date, subject, body_first = head.split("|", 3)
        short = full_hash[:7]

        # 正文第一行被 %s 挤在标题行，其余在 rest；shortstat 混在 rest 末尾，先摘掉
        m = re.search(r"(\d+) files? changed(?:, (\d+) insertions?\(\+\))?(?:, (\d+) deletions?\(-\))?", rest)
        body_rest = rest[: m.start()] if m else rest
        body = "\n".join(p for p in (body_first, body_rest) if p.strip()) or NOTES.get(short, "")
        body = OVERRIDES.get(short, body)  # 含内部话术或转义残留的正文，按仓库实际改动重写

        kind_raw = subject.split(":")[0].split("(")[0].strip().lower()
        title = subject.split(":", 1)[1].strip() if ":" in subject else subject
        title = TITLES.get(short, title)
        phase, artifact = PHASES.get(short, ("未归档", "—"))

        rows.append({
            "日期": date,
            "阶段": phase,
            "类型": KIND.get(kind_raw, "其他"),
            "做了什么": title,
            "为什么这么做 / 怎么做的": flatten(body),
            "改动文件数": int(m.group(1)) if m else 0,
            "代码增删行": f"+{m.group(2) or 0} / -{m.group(3) or 0}" if m else "—",
            "这一步留下了什么": artifact,
            "对应提交": short,
        })

    rows.reverse()  # 老的在前，读起来像时间线
    for i, r in enumerate(rows, 1):
        r["序号"] = i
    return rows


